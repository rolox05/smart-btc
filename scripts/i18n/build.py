"""
Writes the Spanish and Portuguese dictionaries from the translation tables in this folder.

    python3 scripts/i18n/build.py

Each table maps an English source string to (Spanish, Portuguese). The generated files are plain
TypeScript objects, so they can also be edited by hand; this script simply regenerates them.
"""
import json
import pathlib
import runpy

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent

TARGETS = {
    'server': ROOT / 'apps/server/src/i18n',
    'web': ROOT / 'apps/web/src/locales',
}
LANG_NAME = {'es': 'Spanish', 'pt': 'Portuguese'}
DESCRIPTION = {'server': 'Server-generated text', 'web': 'Interface text'}


def write(target: str, table: dict) -> None:
    for i, lang in enumerate(('es', 'pt')):
        lines = [
            "import type { Dict } from '@smart-btc/shared';",
            '',
            f'/** {DESCRIPTION[target]} in {LANG_NAME[lang]}. Keys are the English source strings. Generated by scripts/i18n/build.py. */',
            'const dict: Dict = {',
        ]
        for en, tr in table.items():
            lines.append(f'  {json.dumps(en, ensure_ascii=False)}: {json.dumps(tr[i], ensure_ascii=False)},')
        lines += ['};', '', 'export default dict;', '']
        (TARGETS[target] / f'{lang}.ts').write_text('\n'.join(lines))
    print(f'{target}: {len(table)} entries')


for target in TARGETS:
    path = HERE / f'{target}.py'
    if path.exists():
        write(target, runpy.run_path(str(path))['T'])
